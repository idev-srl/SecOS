#include "signed_test_elf.h"
#include "debugcon.h"

static int eq(const uint8_t* a, const uint8_t* b, int n) {
    for (int i = 0; i < n; i++) if (a[i] != b[i]) return 0;
    return 1;
}

static int report(const char* name, int ok) {
    debugcon_writestring("[CRYPTO] ");
    debugcon_writestring(ok ? "PASS: " : "FAIL: ");
    debugcon_writestring(name);
    debugcon_writestring("\n");
    return ok ? 0 : 1;
}

int crypto_selftest(void) {
    int fails = 0;
    debugcon_writestring("[CRYPTO] --- begin ---\n");

    /* SHA-256("abc") — FIPS 180-4 example */
    {
        static const uint8_t want[32] = {
            0xba,0x78,0x16,0xbf,0x8f,0x01,0xcf,0xea,0x41,0x41,0x40,0xde,0x5d,0xae,0x22,0x23,
            0xb0,0x03,0x61,0xa3,0x96,0x17,0x7a,0x9c,0xb4,0x10,0xff,0x61,0xf2,0x00,0x15,0xad
        };
        uint8_t out[32]; sha256("abc", 3, out);
        fails += report("SHA256(\"abc\")", eq(out, want, 32));
    }

    /* SHA-256("") — empty string */
    {
        static const uint8_t want[32] = {
            0xe3,0xb0,0xc4,0x42,0x98,0xfc,0x1c,0x14,0x9a,0xfb,0xf4,0xc8,0x99,0x6f,0xb9,0x24,
            0x27,0xae,0x41,0xe4,0x64,0x9b,0x93,0x4c,0xa4,0x95,0x99,0x1b,0x78,0x52,0xb8,0x55
        };
        uint8_t out[32]; sha256("", 0, out);
        fails += report("SHA256(\"\")", eq(out, want, 32));
    }

    /* Multi-block / streaming: 1,000,000 'a' should match FIPS vector */
    {
        static const uint8_t want[32] = {
            0xcd,0xc7,0x6e,0x5c,0x99,0x14,0xfb,0x92,0x81,0xa1,0xc7,0xe2,0x84,0xd7,0x3e,0x67,
            0xf1,0x80,0x9a,0x48,0xa4,0x97,0x20,0x0e,0x04,0x6d,0x39,0xcc,0xc7,0x11,0x2c,0xd0
        };
        sha256_ctx c; sha256_init(&c);
        uint8_t blk[64]; for (int i=0;i<64;i++) blk[i]='a';
        for (int i = 0; i < 15625; i++) sha256_update(&c, blk, 64); /* 15625*64 = 1,000,000 */
        uint8_t out[32]; sha256_final(&c, out);
        fails += report("SHA256(1e6 x 'a')", eq(out, want, 32));
    }

    /* SHA-512("abc") — FIPS 180-4 example */
    {
        static const uint8_t want[64] = {
            0xdd,0xaf,0x35,0xa1,0x93,0x61,0x7a,0xba,0xcc,0x41,0x73,0x49,0xae,0x20,0x41,0x31,
            0x12,0xe6,0xfa,0x4e,0x89,0xa9,0x7e,0xa2,0x0a,0x9e,0xee,0xe6,0x4b,0x55,0xd3,0x9a,
            0x21,0x92,0x99,0x2a,0x27,0x4f,0xc1,0xa8,0x36,0xba,0x3c,0x23,0xa3,0xfe,0xeb,0xbd,
            0x45,0x4d,0x44,0x23,0x64,0x3c,0xe8,0x0e,0x2a,0x9a,0xc9,0x4f,0xa5,0x4c,0xa4,0x9f
        };
        uint8_t out[64]; sha512("abc", 3, out);
        fails += report("SHA512(\"abc\")", eq(out, want, 64));
    }

    /* Ed25519 verify — reproducible vector (seed = 00 01 .. 1f, ref: cryptography) */
    {
        static const uint8_t pk[32]   = {0x03,0xa1,0x07,0xbf,0xf3,0xce,0x10,0xbe,0x1d,0x70,0xdd,0x18,0xe7,0x4b,0xc0,0x99,0x67,0xe4,0xd6,0x30,0x9b,0xa5,0x0d,0x5f,0x1d,0xdc,0x86,0x64,0x12,0x55,0x31,0xb8};
        static const uint8_t sig_e[64] = {0x9c,0xa5,0x35,0x79,0x53,0x06,0x54,0xd5,0xc3,0xdf,0x77,0x08,0x9e,0xf4,0x5e,0xda,0x61,0x3e,0x2f,0xed,0xf6,0x70,0xe9,0x6b,0xed,0xac,0x46,0x39,0x50,0x4e,0x58,0x45,0xef,0x4b,0x95,0xd5,0x79,0x30,0x77,0x23,0x3d,0xd1,0x68,0x17,0xb2,0x53,0x2e,0x9c,0x55,0x25,0x87,0x2a,0x73,0xa4,0xad,0x74,0xb7,0x59,0x36,0x9a,0x9e,0x05,0xc1,0x02};
        static const uint8_t sig_m[64] = {0x94,0x20,0xdf,0x5d,0xa2,0xd3,0xb5,0xe9,0x99,0xab,0xca,0x49,0x18,0x5f,0xa1,0x1c,0x3f,0x82,0x9f,0xf2,0x97,0xa4,0x44,0x59,0xc9,0x91,0x00,0x2e,0x02,0xe4,0xb8,0x7f,0x36,0x7b,0x4d,0x02,0x22,0xea,0x83,0xd3,0x47,0xc2,0x90,0x93,0x01,0x65,0x09,0xa7,0xee,0x87,0x70,0x65,0x1b,0x57,0xd5,0x0d,0xa3,0xb2,0x68,0xc7,0xd5,0xd9,0xe8,0x01};
        const char* msg = "SecOS code-signing KAT";

        fails += report("Ed25519 verify(empty)",   ed25519_verify((const uint8_t*)"", 0, sig_e, pk) == 1);
        fails += report("Ed25519 verify(msg)",     ed25519_verify((const uint8_t*)msg, 22, sig_m, pk) == 1);

        /* Negative: tampered signature must be rejected */
        uint8_t bad[64]; for (int i=0;i<64;i++) bad[i]=sig_m[i]; bad[10] ^= 0x01;
        fails += report("Ed25519 reject(tampered sig)", ed25519_verify((const uint8_t*)msg, 22, bad, pk) == 0);
        /* Negative: right sig, wrong message */
        fails += report("Ed25519 reject(wrong msg)",    ed25519_verify((const uint8_t*)"secos code-signing KAT", 22, sig_m, pk) == 0);
    }

    /* ELF signature verification (end-to-end: host-signed DEV ELF vs kernel verify) */
    {
        fails += report("ELF sig verify(valid)",
                        elf_signature_verify(signed_test_elf, signed_test_elf_len) == ELF_SIG_OK);

        static uint8_t buf[1024];
        for (size_t i = 0; i < signed_test_elf_len && i < sizeof(buf); i++) buf[i] = signed_test_elf[i];
        buf[0x100] ^= 0x01; /* flip a code byte -> digest changes */
        fails += report("ELF sig reject(tampered code)",
                        elf_signature_verify(buf, signed_test_elf_len) == ELF_SIG_BAD);

        for (size_t i = 0; i < signed_test_elf_len && i < sizeof(buf); i++) buf[i] = signed_test_elf[i];
        buf[584] ^= 0x01; /* flip a signature byte (QSIG sig @584) */
        fails += report("ELF sig reject(tampered sig)",
                        elf_signature_verify(buf, signed_test_elf_len) == ELF_SIG_BAD);
    }

    debugcon_writestring(fails ? "[CRYPTO] --- FAIL ---\n" : "[CRYPTO] --- all PASS ---\n");
    return fails;
}
