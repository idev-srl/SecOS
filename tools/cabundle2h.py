#!/usr/bin/env python3
# Turn curl's Mozilla CA bundle (cacert-YYYY-MM-DD.pem) into kernel/ca_bundle.h.
# SPDX-License-Identifier: MIT (this script; the certificate data is MPL-2.0,
# docs/licenses/mozilla-ca-bundle-NOTICE)
#
#   python3 -I tools/cabundle2h.py <cacert-YYYY-MM-DD.pem> <out.h>
#
# The PEM text is embedded byte for byte (comments included), so the file a
# guest installs has the same SHA-256 as the one published by curl.se.
# The input is untrusted download data: it is checked to be UTF-8 PEM text
# with only the bundle's own comment lines, and nothing in it is executed.
import hashlib
import re
import sys


def die(msg):
    sys.stderr.write("cabundle2h: %s\n" % msg)
    sys.exit(1)


def main():
    if len(sys.argv) != 3:
        die("usage: cabundle2h.py <cacert-YYYY-MM-DD.pem> <out.h>")
    src, out = sys.argv[1], sys.argv[2]
    m = re.search(r"cacert-(\d{4}-\d{2}-\d{2})\.pem$", src)
    if not m:
        die("input must be named cacert-YYYY-MM-DD.pem")
    date = m.group(1)
    data = open(src, "rb").read()
    if len(data) > 4 * 1024 * 1024:
        die("bundle larger than 4 MiB")
    try:
        text = data.decode("utf-8")     # certificate names may be UTF-8
    except UnicodeDecodeError:
        die("bundle is not UTF-8")
    # Allowed line shapes: "##" comments, blank lines, the certificate name
    # lines and "====" underlines curl writes, and PEM armour/base64.
    inside = False
    ncert = 0
    for n, line in enumerate(text.split("\n"), 1):
        if line == "-----BEGIN CERTIFICATE-----":
            if inside:
                die("line %d: nested BEGIN" % n)
            inside = True
            continue
        if line == "-----END CERTIFICATE-----":
            if not inside:
                die("line %d: END without BEGIN" % n)
            inside = False
            ncert += 1
            continue
        if inside:
            if not re.fullmatch(r"[A-Za-z0-9+/=]{1,76}", line):
                die("line %d: bad base64 line" % n)
        elif any(ord(c) < 0x20 or ord(c) == 0x7f for c in line):
            die("line %d: control character outside a certificate" % n)
    if inside:
        die("unterminated certificate")
    if ncert < 50:
        die("only %d certificates: not a CA bundle?" % ncert)
    if ("Certificate data from Mozilla as of:" not in text
            or not text.startswith("##")):
        die("missing the curl/Mozilla bundle header")
    digest = hashlib.sha256(data).hexdigest()

    def cstr(s):
        # Printable ASCII as is; anything else as 3-digit octal escapes
        # (fixed width, so a following digit can never extend them).
        r = []
        for b in s.encode("utf-8"):
            if b == 0x5c:
                r.append("\\\\")
            elif b == 0x22:
                r.append('\\"')
            elif b == 0x3f:
                r.append("\\?")     # no trigraphs
            elif 0x20 <= b < 0x7f:
                r.append(chr(b))
            else:
                r.append("\\%03o" % b)
        return "".join(r)

    lines = text.split("\n")
    body = []
    for i, line in enumerate(lines):
        nl = "\\n" if i < len(lines) - 1 else ""
        if nl or line:
            body.append('    "%s%s"' % (cstr(line), nl))
    with open(out, "w", encoding="ascii", newline="\n") as f:
        f.write("/* Generated by tools/fetch-cabundle.sh (tools/cabundle2h.py) from\n"
                " * https://curl.se/ca/cacert-%s.pem. Do not edit by hand.\n"
                " * Mozilla's CA certificate set as extracted by curl (mk-ca-bundle).\n"
                " * Data licence: MPL-2.0 (docs/licenses/mozilla-ca-bundle-NOTICE). */\n"
                % date)
        f.write("#ifndef CA_BUNDLE_H\n#define CA_BUNDLE_H\n")
        f.write('#define CA_BUNDLE_DATE "%s"\n' % date)
        f.write('#define CA_BUNDLE_SHA256 "%s"\n' % digest)
        f.write("#define CA_BUNDLE_CERTS %d\n" % ncert)
        f.write("static const char ca_bundle_pem[] =\n")
        f.write("\n".join(body))
        f.write(";\n")
        f.write("#define CA_BUNDLE_PEM_LEN (sizeof(ca_bundle_pem) - 1)\n")
        f.write("#endif\n")
    sys.stderr.write("[cabundle2h] %s: %d certificates, %d bytes, sha256 %s -> %s\n"
                     % (date, ncert, len(data), digest, out))


if __name__ == "__main__":
    main()
