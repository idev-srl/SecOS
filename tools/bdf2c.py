#!/usr/bin/env python3
# tools/bdf2c.py - turn 8x16 BDF fonts into a C glyph table for user programs.
# SPDX-License-Identifier: MIT
#
#   python3 tools/bdf2c.py OUT.h REGULAR.bdf [BOLD.bdf]
#
# Keeps the code points SecOS user interfaces need (ASCII, Latin-1, general
# punctuation, the Euro sign, arrows, box drawing, block elements, geometric
# shapes and U+FFFD) and writes them as a table sorted by code point, so a
# reader can binary-search it. Every glyph is 16 rows of one byte, bit 7 = the
# leftmost pixel. The glyph bitmaps are copied unchanged; only the container
# format changes (BDF -> C array). Used for user/secwm/font16.h from the
# vendored Terminus Font in third_party/terminus-font/ (SIL OFL 1.1).
import sys

RANGES = [(0x20, 0x7E), (0xA0, 0xFF), (0x2010, 0x2027), (0x2030, 0x203A), (0x20AC, 0x20AC),
          (0x2190, 0x2195), (0x2500, 0x259F), (0x25A0, 0x25CF), (0x2713, 0x2714), (0xFFFD, 0xFFFD)]

def wanted(cp):
    return any(a <= cp <= b for a, b in RANGES)

def load(path):
    glyphs = {}
    enc = None; bits = None; bbx = None
    with open(path, encoding="latin-1") as f:
        for line in f:
            w = line.split()
            if not w: continue
            if w[0] == "ENCODING": enc = int(w[1])
            elif w[0] == "BBX": bbx = tuple(int(v) for v in w[1:5])
            elif w[0] == "BITMAP": bits = []
            elif w[0] == "ENDCHAR":
                if enc is not None and bits is not None and wanted(enc):
                    if bbx != (8, 16, 0, -4) or len(bits) != 16:
                        sys.exit("bdf2c: %s: U+%04X is not an 8x16 cell" % (path, enc))
                    glyphs[enc] = bits
                enc = None; bits = None
            elif bits is not None:
                bits.append(int(w[0], 16))
    return glyphs

def main():
    if len(sys.argv) not in (3, 4):
        sys.exit("usage: bdf2c.py OUT.h REGULAR.bdf [BOLD.bdf]")
    reg = load(sys.argv[2])
    bold = load(sys.argv[3]) if len(sys.argv) == 4 else reg
    cps = sorted(cp for cp in reg if cp in bold)
    out = []
    out.append("/* Generated by tools/bdf2c.py from %s%s - do not edit." % (
        sys.argv[2].split("/")[-1], (" + " + sys.argv[3].split("/")[-1]) if len(sys.argv) == 4 else ""))
    out.append(" *")
    out.append(" * Glyph bitmaps from Terminus Font, Copyright (C) 2020 Dimitar Toshkov Zhekov,")
    out.append(" * licensed under the SIL Open Font License, Version 1.1")
    out.append(" * (third_party/terminus-font/OFL.TXT). Subset of %d code points, format" % len(cps))
    out.append(" * converted to a C table; the glyph shapes are unchanged. */")
    out.append("#ifndef SECOS_FONT16_H")
    out.append("#define SECOS_FONT16_H")
    out.append("#include <stdint.h>")
    out.append("#define FONT16_W 8")
    out.append("#define FONT16_H 16")
    out.append("#define FONT16_N %d" % len(cps))
    out.append("static const uint16_t font16_cp[FONT16_N] = {")
    for i in range(0, len(cps), 12):
        out.append("    " + ", ".join("0x%04X" % c for c in cps[i:i + 12]) + ",")
    out.append("};")
    for name, src in (("font16_reg", reg), ("font16_bold", bold)):
        out.append("static const uint8_t %s[FONT16_N][16] = {" % name)
        for c in cps:
            out.append("    {" + ",".join("0x%02X" % b for b in src[c]) + "}, /* U+%04X */" % c)
        out.append("};")
    out.append("#endif")
    with open(sys.argv[1], "w") as f:
        f.write("\n".join(out) + "\n")
    print("bdf2c: %d glyphs -> %s" % (len(cps), sys.argv[1]))

main()
