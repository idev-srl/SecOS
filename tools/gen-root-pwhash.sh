#!/usr/bin/env bash
# SecOS - write build/root_pwhash.h for `make ROOT_PASSWORD=...` (or
# ROOT_PASSWORD_HASH=...). Usage: gen-root-pwhash.sh OUT.h
#
#   ROOT_PASSWORD       plain password (environment only: the Makefile exports
#                       it to this script, it is never put on a command line).
#                       Hashed with SHA-512 crypt by tools/pwhash_host (the
#                       vendored musl crypt, same code as the guest).
#   ROOT_PASSWORD_HASH  a ready-made crypt hash ($6$..., e.g. from
#                       `openssl passwd -6`), used as is.
#   neither             SECOS_ROOT_PWHASH is "" and the kernel sets nothing.
#
# OUT.h is rewritten only when its content would change: an unchanged
# password keeps the existing hash (verified), so the kernel is not rebuilt
# and the salt does not change on every build. Only the hash reaches the
# image; the plain password is never written anywhere.
# SPDX-License-Identifier: MIT
set -euo pipefail
OUT=$1
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
MC="$ROOT/third_party/musl-crypt"
mkdir -p "$(dirname "$OUT")"

emit() {  # emit HASH
    local tmp="$OUT.tmp"
    { echo "/* Generated by tools/gen-root-pwhash.sh (make ROOT_PASSWORD=...). Do not commit. */"
      echo "#define SECOS_ROOT_PWHASH \"$1\""; } > "$tmp"
    if cmp -s "$tmp" "$OUT" 2>/dev/null; then rm -f "$tmp"; else mv "$tmp" "$OUT"; fi
}

current() {  # the hash in OUT.h, if any
    [[ -f "$OUT" ]] && sed -n 's/^#define SECOS_ROOT_PWHASH "\(.*\)"$/\1/p' "$OUT" || true
}

if [[ -n "${ROOT_PASSWORD_HASH:-}" ]]; then
    case "$ROOT_PASSWORD_HASH" in
        \$6\$*|\$5\$*|\$2b\$*) ;;
        *) echo "gen-root-pwhash: ROOT_PASSWORD_HASH must be a \$6\$/\$5\$/\$2b\$ crypt hash" >&2; exit 1 ;;
    esac
    if [[ "$ROOT_PASSWORD_HASH" == *[\":\\]* || "$ROOT_PASSWORD_HASH" == *[[:space:]]* ]]; then
        echo "gen-root-pwhash: ROOT_PASSWORD_HASH contains invalid characters" >&2; exit 1
    fi
    emit "$ROOT_PASSWORD_HASH"
    exit 0
fi
if [[ -z "${ROOT_PASSWORD:-}" ]]; then
    emit ""
    exit 0
fi

TOOL="$(dirname "$OUT")/pwhash_host"
SRCS=("$MC/src/crypt/crypt.c" "$MC/src/crypt/crypt_sha256.c" "$MC/src/crypt/crypt_sha512.c"
      "$MC/src/crypt/crypt_blowfish.c" "$ROOT/user/crypt_glue.c" "$ROOT/user/pwhash.c"
      "$ROOT/tools/pwhash_host/pwhash_host.c")
if [[ ! -x "$TOOL" ]] || [[ -n "$(find "${SRCS[@]}" -newer "$TOOL" 2>/dev/null)" ]]; then
    gcc -std=c99 -D_XOPEN_SOURCE=700 -O2 -w -I"$MC/src/include" -Dhidden= \
        -iquote "$ROOT/user" -iquote "$ROOT/user/include" -o "$TOOL" "${SRCS[@]}"
fi
OLD="$(current)"
if [[ -n "$OLD" ]] && "$TOOL" verify "$OLD"; then
    exit 0                      # same password: keep the hash (and its salt)
fi
emit "$("$TOOL" hash)"
echo "[root-password] root password hash baked into build/root_pwhash.h"
