#!/usr/bin/env python3
"""Bake SSH public keys into the kernel image (make SSH_AUTHORIZED_KEYS=...).

Usage: gen-authorized-keys.py OUT.h [KEYFILE...]

Writes a C header defining SECOS_AUTHORIZED_KEYS (the authorized_keys text) and
SECOS_AUTHORIZED_KEYS_LEN. With no key file the length is 0 and the kernel
installs nothing (SSH then refuses every login). OUT.h is rewritten only when
its content changes, so an unchanged key set does not rebuild the kernel.

Only public keys are accepted: a line that looks like a private key, or that
does not start with a known public-key type (optionally after authorized_keys
options), makes the build fail.
"""
import os
import sys

KEY_TYPES = ("ssh-ed25519", "ssh-rsa", "ecdsa-sha2-", "sk-ssh-ed25519@", "sk-ecdsa-sha2-",
             "ssh-dss")


def fail(msg):
    sys.stderr.write("gen-authorized-keys: %s\n" % msg)
    sys.exit(1)


def valid_line(line):
    if line.startswith(KEY_TYPES):
        return True
    # authorized_keys options before the key: `command="...",no-pty ssh-ed25519 AAAA...`
    return any((" " + t) in line for t in KEY_TYPES)


def main():
    if len(sys.argv) < 2:
        fail("usage: gen-authorized-keys.py OUT.h [KEYFILE...]")
    out = sys.argv[1]
    lines = []
    for path in sys.argv[2:]:
        if not path:
            continue
        try:
            with open(path, "r", encoding="utf-8") as f:
                text = f.read()
        except OSError as e:
            fail("cannot read %s: %s" % (path, e))
        if "PRIVATE KEY" in text:
            fail("%s looks like a PRIVATE key; pass the .pub file" % path)
        for raw in text.splitlines():
            line = raw.strip()
            if not line or line.startswith("#"):
                continue
            if not valid_line(line):
                fail("%s: not a public key line: %.40s..." % (path, line))
            lines.append(line)
    if sys.argv[2:] and any(sys.argv[2:]) and not lines:
        fail("no public key found in %s" % " ".join(sys.argv[2:]))
    body = "".join(l + "\n" for l in lines)
    esc = body.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")
    hdr = ("/* Generated by tools/gen-authorized-keys.py from SSH_AUTHORIZED_KEYS.\n"
           " * Do not commit (build/ is ignored). %d key(s). */\n"
           "#define SECOS_AUTHORIZED_KEYS \"%s\"\n"
           "#define SECOS_AUTHORIZED_KEYS_LEN %d\n") % (len(lines), esc, len(body.encode()))
    old = None
    if os.path.exists(out):
        with open(out, "r", encoding="utf-8") as f:
            old = f.read()
    if old != hdr:
        os.makedirs(os.path.dirname(out) or ".", exist_ok=True)
        with open(out, "w", encoding="utf-8") as f:
            f.write(hdr)
        print("gen-authorized-keys: %s updated (%d key(s))" % (out, len(lines)))


if __name__ == "__main__":
    main()
