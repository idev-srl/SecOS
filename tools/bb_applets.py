#!/usr/bin/env python3
# SecOS - emit kernel/busybox_applets.h (the applet names the kernel installs
# under /bin as signed stubs) from BusyBox's generated include/applet_tables.h.
# Usage: bb_applets.py <applet_tables.h> <out.h>
# SPDX-License-Identifier: MIT
import re
import sys

src, out = sys.argv[1], sys.argv[2]
txt = open(src).read()
body = txt[txt.index('applet_names[]'):]
body = body[:body.index(';')]
names = [n for n in re.findall(r'"([^"]*)" "\\0"', body) if n]
lines = ['/* Generated by tools/bb_applets.py from BusyBox include/applet_tables.h.',
         ' * The applets compiled into the signed /bin/busybox (see user/busybox.config).',
         ' * SPDX-License-Identifier: MIT */',
         '#ifndef SECOS_BUSYBOX_APPLETS_H',
         '#define SECOS_BUSYBOX_APPLETS_H',
         '#define BUSYBOX_NUM_APPLETS %d' % len(names),
         'static const char* const busybox_applets[] = {']
row = '   '
for n in names:
    item = ' "%s",' % n
    if len(row) + len(item) > 96:
        lines.append(row)
        row = '   '
    row += item
lines.append(row + ' 0')
lines += ['};', '#endif', '']
open(out, 'w').write('\n'.join(lines))
